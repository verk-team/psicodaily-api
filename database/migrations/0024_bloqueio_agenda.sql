-- Ferias e folgas do profissional: dias inteiros, com inicio e fim inclusivos. Vale em todos os planos.
CREATE TABLE BLOQUEIO_AGENDA (BLOQUEIO_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        PROFISSIONAL_ID INTEGER NOT NULL,
        DATA_INICIO DATE NOT NULL,
        DATA_FIM DATE NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (BLOQUEIO_ID),
CONSTRAINT CK_BLOQUEIO_AGENDA_DATAS CHECK (DATA_FIM >= DATA_INICIO));
ALTER TABLE BLOQUEIO_AGENDA ADD CONSTRAINT FK_BLOQUEIO_AGENDA_PROFISSIONAL FOREIGN KEY (PROFISSIONAL_ID) REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE;
