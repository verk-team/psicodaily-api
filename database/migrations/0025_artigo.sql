-- A tabela continua CONTEUDO (renomear seria destrutivo). Artigos antigos ficam com SUBTITULO NULL; os novos exigem.
ALTER TABLE CONTEUDO ADD SUBTITULO VARCHAR(300) CHARACTER SET UTF8;

CREATE TABLE CURTIDA_ARTIGO (CONTEUDO_ID INTEGER NOT NULL,
        USUARIO_ID INTEGER NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (CONTEUDO_ID, USUARIO_ID));
ALTER TABLE CURTIDA_ARTIGO ADD CONSTRAINT FK_CURTIDA_ARTIGO_CONTEUDO FOREIGN KEY (CONTEUDO_ID) REFERENCES CONTEUDO (CONTEUDO_ID) ON DELETE CASCADE;
ALTER TABLE CURTIDA_ARTIGO ADD CONSTRAINT FK_CURTIDA_ARTIGO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE;
